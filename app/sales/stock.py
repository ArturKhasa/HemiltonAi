"""Позиции, снятые с продажи — «стоп на цвет».

Лена, 04.09: «У нас размерная сетка динамичная, вчера распродали один из цветов
для свитшотов. Я в скриптах заменила картинку, но ИИ до сих пор знает, что этот
цвет у нас в наличии. Как поставить определённый цвет на стоп?»

Фото в скрипте — не тот рычаг: палитра лежит одной общей картинкой на все цвета
сразу (app.sales.color_palette), и подменой файла ничего «выключить» нельзя.
Рычаг есть, и он один — галочка «Активен» у строки товарной матрицы: по ней уже
фильтруется поиск товара (ProductService), то есть на прямой вопрос «а чёрный
есть?» агент отвечает верно. Не хватало двух вещей:

* модель об этом не знала заранее и продолжала предлагать снятый цвет сама;
* палитра уходила клиенту как есть — со всеми цветами, включая распроданный.

Обе дырки закрываются отсюда: список снятых позиций уходит в контекст хода
отдельным блоком, а к картинке-палитре дописывается оговорка, каких цветов
сейчас нет.

Гранулярность — цвет целиком, без размеров: ответ заказчика 05.09 на вопрос
В1 плана — «пока достаточно только цвета». Размера в товарной матрице нет
вовсе, это отдельная доработка модели данных.
"""
import re

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.models import Product

# Слова, обозначающие само изделие: из названия позиции их убираем, чтобы в
# оговорке к палитре остался только цвет. Матрицу заполняют руками и порядок
# слов в ней скачет («Свитшот Черный», но «Черный худи»), поэтому вырезаем
# по словам, а не по позиции.
_PRODUCT_WORDS_RE = re.compile(
    r"\b(?:свитшот\w*|зип-худи|худи|толстовк\w+|жилетк\w+|футболк\w+|лонгслив\w*|"
    r"кепк\w+|кед\w+|носк\w+|костюм\w*|рюкзак\w*|поло|топ)\b",
    re.I,
)

# К какой палитре относится позиция. Палитр всего две — свитшота и худи
# (см. app.sales.color_palette), у остального своей картинки нет.
_HOODIE_ITEM_RE = re.compile(r"худи", re.I)
_SWEATSHIRT_ITEM_RE = re.compile(r"свитшот", re.I)


async def sold_out_names(db: AsyncSession, type_id: int | None = None) -> list[str]:
    """Названия позиций, у которых снята галочка «Активен»."""
    q = select(Product.name).where(Product.is_active == False)
    if type_id is not None:
        q = q.where(Product.type_id == type_id)
    rows = await db.execute(q.order_by(Product.id))
    return [name.strip() for name in rows.scalars().all() if (name or "").strip()]


def format_sold_out_block(names: list[str]) -> str:
    """Блок контекста «этого сейчас нет» — или пустая строка, если всё в наличии."""
    if not names:
        return ""
    listed = "\n".join(f"- {name}" for name in names)
    return (
        "[Нет в наличии]\n"
        f"{listed}\n"
        "Этих позиций сейчас нет. Не предлагай их, не показывай как вариант и не "
        "подтверждай заказ в них. Спросят про такую — скажи прямо, что её сейчас "
        "нет, и предложи то, что есть."
    )


def color_of(name: str) -> str:
    """Цвет из названия позиции матрицы: «Свитшот Черный» → «черный».

    Название не разбираем на составляющие: убираем слова про само изделие, а
    остаток отдаём как есть. Если после вырезания ничего не осталось (позиция
    называется одним словом — «Рюкзак»), возвращаем исходное название: лучше
    сказать длинно, чем пусто.
    """
    stripped = _PRODUCT_WORDS_RE.sub(" ", name or "")
    stripped = re.sub(r"\s{2,}", " ", stripped).strip(" -—,")
    return stripped.lower() if stripped else (name or "").strip().lower()


def sold_out_colors(names: list[str], wants_hoodie: bool) -> list[str]:
    """Цвета снятых позиций той палитры, которую сейчас показываем.

    Позиции без изделия из палитры (подарки, вышивка, кепки) сюда не попадают:
    к картинке с цветами свитшота они отношения не имеют.
    """
    matcher = _HOODIE_ITEM_RE if wants_hoodie else _SWEATSHIRT_ITEM_RE
    colors = []
    for name in names:
        if not matcher.search(name or ""):
            continue
        # «Черный зип-худи» — это отдельная позиция, а не цвет обычного худи:
        # в палитре худи его нет, и оговорка про него собьёт с толку.
        if not wants_hoodie and _HOODIE_ITEM_RE.search(name or ""):
            continue
        color = color_of(name)
        if color and color not in colors:
            colors.append(color)
    return colors
