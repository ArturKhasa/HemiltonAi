"""Условия акции, которые модель достраивает за нас.

В скрипте «5. Оформление» написано ровно столько: «внести всю сумму и получить
подарок на выбор — кепку с нашивкой флага РФ или белую футболку». Ни срока
действия, ни запрета взять оба подарка там нет, и на прямую просьбу клиента
модель отвечает согласием — а живой менеджер потом отыгрывает обещание назад.
Диалог 343 за две минуты собрал все три ошибки сразу:

    08:55  «После оплаты пришлите ФИО и телефон получателя»
    08:57  «Да, можно выбрать оба подарка — кепку и белую футболку»
    08:57  «При оплате всей суммы завтра зафиксирую оба подарка»

Правила ОП: данные получателя нужны ДО счёта (иначе счёт не из чего выставить),
подарок ровно один на выбор, подарок и скидка действуют только при оплате в день
обращения — на другой день оформляется бронь.

Проверки идут по предложениям, а не по всему тексту: «После оплаты пришлите чек»
и просьба про ФИО в разных предложениях — это нормальный ход, а те же слова в
одном предложении меняют смысл на обратный.
"""
import re

from app.sales.order_slots import asked_slot

# Границы предложения: точка/!/? либо перенос строки — скрипты разбиты строками.
_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?…])\s+|\n+")

# «После оплаты», «как оплатите», «после внесения предоплаты».
_AFTER_PAYMENT_RE = re.compile(
    r"(?:после|как\s+только)\s+(?:оплат\w*|внес\w*|перевод\w*|поступ\w*)"
    r"|как\s+(?:оплатите|внесёте|внесете|переведёте|переведете)"
    r"|оплатите\s+и\s+(?:пришлите|напишите|скиньте)",
    re.I,
)

# Подарок и скидка — то, что нельзя пообещать на другой день и нельзя удвоить.
_OFFER_RE = re.compile(r"подар\w*|подарочек|скидк\w*|акци\w*", re.I)

# Оба подарка вместо одного. Второй вариант — «кепка и белая футболка будут
# подарками»: перечисление через «и» с подарком в том же предложении.
_BOTH_GIFTS_RE = re.compile(
    r"об[аое]\s+подар\w*"
    r"|два\s+подар\w*"
    r"|и\s+кепк\w*\s*,?\s*и\s+(?:бел\w+\s+)?(?:футболк|майк)\w*"
    r"|кепк\w*\s+и\s+(?:бел\w+\s+)?(?:футболк|майк)\w*.{0,25}подар",
    re.I,
)

# Перенос оплаты на другой день. «Позже», «потом», «как будет удобно» сюда НЕ
# входят: ими заканчиваются скрипты брони («к работе приступить, как Вам будет
# удобно»), и это как раз правильный ответ на перенос.
_ANOTHER_DAY_RE = re.compile(
    r"завтра|послезавтра|на\s+следующей\s+неделе|через\s+недел\w*"
    r"|на\s+выходн\w*|в\s+выходн\w*|после\s+зарплат\w*"
    r"|в\s+(?:понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье)",
    re.I,
)

_PAYMENT_RE = re.compile(
    r"оплат\w*|оплатит\w*|внес\w*|внесёт\w*|внесет\w*|перевед\w*|заказ\w*\s+оформ\w*",
    re.I,
)

# Бронь — законный способ удержать цену и подарок к другой дате, её не трогаем.
_BOOKING_RE = re.compile(r"брон\w*|заброниру\w*|предоплат\w*", re.I)


def _sentences(text: str) -> list[str]:
    return [s for s in _SENTENCE_SPLIT_RE.split(text or "") if s.strip()]


def data_requested_after_payment(text: str) -> bool:
    """Реплика просит ФИО и телефон ПОСЛЕ оплаты.

    Порядок обратный: счёт выставляется по этим данным, значит собрать их надо
    раньше. Клиент, понявший буквально, заплатит и останется без оформления.
    """
    return any(
        asked_slot(s) == "recipient" and _AFTER_PAYMENT_RE.search(s)
        for s in _sentences(text)
    )


def promises_both_gifts(text: str) -> bool:
    """Реплика обещает оба подарка сразу — кепку и футболку."""
    return bool(_BOTH_GIFTS_RE.search(text or ""))


def promises_offer_another_day(text: str) -> bool:
    """Реплика обещает подарок или скидку за оплату не сегодня.

    Ищем в одном предложении три вещи разом: подарок/скидку, перенос на другой
    день и саму оплату. Предложение про бронь пропускаем — там перенос законен.
    """
    for s in _sentences(text):
        if _BOOKING_RE.search(s):
            continue
        if _OFFER_RE.search(s) and _ANOTHER_DAY_RE.search(s) and _PAYMENT_RE.search(s):
            return True
    return False


# Стоимость доставки. Лена, 21.08: «Можно зафиксировать, что стоимость доставки
# СДЭКом фикс. по всем направлениям - 1000р, она оплачивается при получении
# после просмотра и примерки».
#
# Суммы не было нигде — ни в скриптах, ни в промпте, ни в матрице, — и на прямой
# вопрос «а доставка сколько стоить будет?» модель отвечала обтекаемо: «её
# стоимость зависит от города» (диалог 75800, 20.08 23:15). То есть придумывала.
DELIVERY_PRICE_RUB = 1000

_DELIVERY_RE = re.compile(r"доставк\w*|сдэк|почт\w*\s+росси", re.I)
_HEDGE_RE = re.compile(
    r"зависит\s+от\s+(?:город|региона|направлен|адрес|веса|расстоян)\w*"
    r"|уточн\w+[^.!?\n]{0,20}(?:стоимость|цену|сумму)"
    r"|(?:стоимость|цена|цену|сумму)[^.!?\n]{0,20}уточн\w+"
    r"|рассчита\w+\s+(?:позже|позднее|при\s+оформлени\w*)"
    r"|назов\w+\s+(?:позже|позднее)"
    r"|(?:стоимость|цена)\s+будет\s+известна",
    re.I,
)


def hedges_delivery_price(text: str) -> bool:
    """Реплика уходит от суммы доставки вместо того, чтобы её назвать."""
    return any(
        _DELIVERY_RE.search(s) and _HEDGE_RE.search(s) for s in _sentences(text)
    )


# «Уточню у руководителя отдела продаж и вернусь с ответом» — фраза из регламента,
# которой ИИ отвечает на срочные сроки и на всё, чего не решает сама. Обещание
# честное, но исполнить его некому: следующего хода у ИИ нет, сам он к клиенту не
# возвращается, и куратора эта фраза не поднимала. За неделю ушла трижды — трое
# клиентов ждут ответа, которого не будет.
#
# Поэтому обещание вернуться = вызов куратора. Либо человек подхватывает диалог,
# либо такую фразу писать нельзя.
_PROMISES_RETURN_RE = re.compile(
    r"уточн\w+\s+(?:у|с)\s+(?:руководител\w+|рук\.?\s*отдела|производств\w+|дизайнер\w+)"
    r"|вернусь\s+с\s+(?:ответом|информацией|уточнением)"
    r"|(?:уточню|узнаю|спрошу)\W[^.!?\n]{0,40}\bи\s+вернусь"
    r"|сообщу\s+(?:позже|дополнительно|как\s+только)"
    r"|напишу\s+(?:вам\s+)?(?:позже|как\s+только\s+узна\w+)",
    re.I,
)


def promises_to_return(text: str) -> bool:
    """Реплика обещает вернуться с ответом — сам ИИ этого сделать не может."""
    return bool(_PROMISES_RETURN_RE.search(text or ""))
