"""Готовит новую версию регламента: 5 точечных правок к активной версии 26."""
import asyncio, asyncpg, os, sys, difflib

DSN = os.environ["DATABASE_URL"].replace("+asyncpg", "")

EDITS = [
    # 1. Похвала перестаёт быть безусловной
    ("""**2. Похвала → стоимость → доставка** — клиент ответил, что писать на изделии.""",
     """**2. Похвала → стоимость → доставка** — клиент НАЗВАЛ имя или фамилию для нанесения."""),
    ("""сообщениями. Назовёшь цену здесь — клиент получит две разные суммы подряд.""",
     """сообщениями. Назовёшь цену здесь — клиент получит две разные суммы подряд.
Если клиент вместо ответа отказался («не надо», «ничего не нужно»), переспросил
(«что?», «м?») или задал свой вопрос — присоединяться НЕ к чему: фиксировать
нечего. Ответь на то, что он написал, и вернись к вопросу про надпись."""),

    # 2. Сверка дизайна — раскладкой, а не пересказом
    ("""**5. Дизайн** — размер известен. Согласуй словами, что и где размещаем, и
перечисли клиенту всё собранное: надпись, изделие, цвет, размер, элементы дизайна.
Ничего не потеряй и не придумай за клиента. Закрой ход вопросом «всё верно?».""",
     """**5. Дизайн** — размер известен. Согласуй РАСКЛАДКУ нанесений: что и где
размещаем. Имя по умолчанию — на груди справа, фамилия — на спине с гербом; «по
центру» имена и фамилии не наносим. В раскладку попадает только то, что клиент
назвал сам. Цвет, размер и цену заново не перечисляй — они уже согласованы, и
повтор читается как допрос. Закрой ход вопросом «всё верно?»."""),

    # 3. Ступени скидки вместо «ниже некуда»
    ("""- Акционная цена — это уже максимальная скидка. Ниже неё скидок нет, и намекать,
  что будет дешевле, нельзя.""",
     """- Ступеней уступки три: обычная цена → цена со скидкой → минимальная. Спускаться
  можно только по одной ступени за ПОВТОРНОЕ ценовое возражение, и только по
  скрипту отработки. Сама вниз не иди и не намекай, что будет дешевле."""),

    # 4. Пример на нижней ступени убираем
    ("""- Несколько изделий — сначала цена ЗА ШТУКУ, потом итог: «4 990 ₽ за штуку, за
  два — 9 980 ₽». Голый итог после цены за штуку читается как подорожание.""",
     """- Несколько изделий — сначала цена ЗА ШТУКУ, потом итог: голый итог после цены
  за штуку читается как подорожание. Обе цифры бери из скрипта или из
  `search_products`, своих не считай."""),

    # 5. Отказ: сначала причина, потом прощание
    ("""- Клиент отказался ПОВТОРНО после твоей попытки дожать — отпусти без давления.""",
     """- Причину отказа выясняй ВСЕГДА: «не надо», «ничего не нужно», «подумаю» — это
  не конец разговора, а повод спросить, что именно не подошло. Не прощайся
  фразами «если решите — напишите», «когда будет удобно», «буду на связи»: после
  них клиент не возвращается.
- И только когда клиент отказался ПОВТОРНО, уже после твоей отработки названной
  им причины, — отпусти без давления."""),
]


async def main():
    c = await asyncpg.connect(DSN, statement_cache_size=0)
    row = await c.fetchrow("select id, name, type_id, content from prompt_versions where is_active")
    old = row["content"]
    new = old
    for i, (before, after) in enumerate(EDITS, 1):
        if before not in new:
            print(f"!!! правка {i} не нашла своё место — прерываю")
            await c.close()
            sys.exit(1)
        new = new.replace(before, after, 1)

    diff = difflib.unified_diff(
        old.splitlines(), new.splitlines(),
        fromfile=f"регламент v{row['id']}", tofile="регламент v(новая)", lineterm="", n=1,
    )
    print("\n".join(diff))
    print(f"\nбыло {len(old)} символов, стало {len(new)}")

    if "--apply" in sys.argv:
        async with c.transaction():
            await c.execute("update prompt_versions set is_active = false where is_active")
            next_id = await c.fetchval("select max(id) + 1 from prompt_versions")
            new_id = await c.fetchval(
                "insert into prompt_versions"
                " (name, version, type_id, content, is_active, created_at)"
                " values ($1, $2, $3, $4, true, now()) returning id",
                row["name"], f"v{next_id}", row["type_id"], new,
            )
        print(f"\nПРИМЕНЕНО: создана версия {new_id}, версия {row['id']} выключена")
    await c.close()

asyncio.run(main())
