"""Просьба показать изделие — на неё отвечают фотографией, а не текстом.

Клиент в диалоге 362 написал «как она будет выглядеть», и модель отправила ему
скрипт «Преимущества/возражение: что получается клиент» — «мы не маркетплейс и
не магазин готовой одежды», пять галочек про этапы производства и ни одной
картинки. Просьба посмотреть возражением не была, а на возражение ответили.

Определяем такую просьбу отдельно: список формулировок короткий, а цена ошибки
высокая — клиент, которому нечего разглядывать, уходит.
"""
import re

# «как она будет выглядеть», «покажите примеры работ», «фото есть?», «можно
# посмотреть», «скиньте фотки». Просьбу прислать КАТАЛОГ сюда не берём — на неё
# есть свой скрипт и своё правило в промпте.
_ASKS_TO_SEE_RE = re.compile(
    r"как\s+(?:он[аи]?|это|изделие|свитшот\w*|худи|толстовк\w*|кофт\w*)?\s*"
    r"(?:буд\w+\s+)?выгляд\w+"
    r"|как\s+выгляд\w+"
    r"|покаж\w+\s+(?:фото|картинк\w*|примеры|как|издели\w*|варианты)"
    r"|примеры\s+(?:работ|изделий|ваших)"
    r"|(?:есть|скинь\w*|пришли\w*|отправь\w*|можно)\s+(?:ещё\s+|еще\s+)?"
    r"(?:фото|фотк\w*|фотографи\w*|картинк\w*)"
    r"|можно\s+(?:по)?смотреть"
    r"|хочу\s+(?:по)?смотреть",
    re.I,
)

_PHOTO_TOKEN_RE = re.compile(r"\[photo-[^\]]+\]")


def asks_to_see_product(text: str) -> bool:
    """Клиент просит показать изделие или примеры работ."""
    return bool(_ASKS_TO_SEE_RE.search(text or ""))


def reply_shows_photo(text: str, image_urls: list[str] | None = None) -> bool:
    """В ответе есть картинка — токеном или уже разобранной ссылкой."""
    return bool(image_urls) or bool(_PHOTO_TOKEN_RE.search(text or ""))


# «Фото-пример с этими именами и фамилиями уже отправила», «Фото отправилось
# выше в переписке» — отсылка к прошлому сообщению вместо картинки. Клиент в
# диалоге 75853 четырежды ответил, что никакого примера с надписями не видит:
# отправлено ему было стоковое фото белых свитшотов без единой надписи.
#
# Честный ход тут один — приложить картинку заново; макета с надписями клиента у
# ИИ нет вовсе, его рисует дизайнер после брони.
_CLAIMS_SENT_RE = re.compile(
    r"уже\s+(?:отправ|показал|скинул|прислал|высла)\w+"
    r"|отправ\w+\s+(?:выше|ранее|раньше)"
    r"|выше\s+в\s+переписке"
    r"|отправилось|отправлено\s+выше",
    re.I,
)
_MEANS_PICTURE_RE = re.compile(r"макет|фото|картинк|пример|образ(?:ец|ц)", re.I)


def claims_picture_already_sent(text: str) -> bool:
    """Ответ отсылает клиента к картинке, которую якобы уже отправляли."""
    body = text or ""
    return bool(_CLAIMS_SENT_RE.search(body) and _MEANS_PICTURE_RE.search(body))
