"""Отличить рассылку от ответа менеджера.

Любое исходящее сообщение группы ставит ИИ на паузу: код читает его как «диалог
забрал живой оператор» (см. `webhook._handle_outgoing`). Для ответа менеджера это
правильно, для массовой рассылки — нет.

20–22 августа по базе прошли 72 шаблона рассылок — «Вы помните, что сегодня День
Государственного флага?», «костюм за 1 руб.», «Имя Ибрагим Вам что-нибудь
говорит?» — в десятки тысяч диалогов. Из 262 диалогов того периода, где ИИ
замолчала, **106 заглушила именно рассылка**, а не человек. Отсюда и замечание ОП
от 21.08, 17:26: «ИИ здесь остановилась, ничего не отвечает клиенту больше».

Отличаем по разлёту: ответ менеджера уходит в один диалог, рассылка — в сотни за
считанные минуты. Счётчик держим в памяти процесса: запрос в базу на каждое
исходящее не окупается, а рассылка пробивает любой разумный порог задолго до
того, как счётчик успеет разъехаться между воркерами.

Первые `_MIN_DIALOGS` диалогов рассылки паузу всё же получат — их видно раньше,
чем становится понятно, что это рассылка. Задним числом снимать паузу не
пытаемся: цена ошибки (вернуть ИИ в диалог, который правда забрал менеджер) выше,
чем десяток диалогов, которые подхватит человек.
"""
import logging
import re
import time

logger = logging.getLogger(__name__)

# Сколько разных диалогов должны получить один и тот же текст, чтобы считать его
# рассылкой. Менеджер столько одинаковых сообщений руками не напишет.
_MIN_DIALOGS = 10
# За какое время. Рассылка укладывается в минуты, у нас с запасом.
_WINDOW_SEC = 1800
# Сколько текстов помним. Шаблонов рассылки за три дня было 72.
_MAX_TRACKED = 2000

# Обращение по имени в начале: «Александр, костюм за 1 руб. — не ошибка.»
# Персонализированная рассылка отличается только им, поэтому имя срезаем.
_LEADING_NAME_RE = re.compile(r"^\s*[А-ЯЁA-Z][а-яёa-z]+\s*[,!]\s*")
# По первым двум сотням символов: дальше рассылки расходятся подписями и ссылками.
_KEY_LEN = 200

# {ключ текста: (первое появление, множество диалогов)}
_seen: dict[str, tuple[float, set[int]]] = {}


def _key(text: str) -> str:
    return _LEADING_NAME_RE.sub("", text or "").strip()[:_KEY_LEN].lower()


def _forget_old(now: float) -> None:
    for key in [k for k, (first, _) in _seen.items() if now - first > _WINDOW_SEC]:
        del _seen[key]
    # Аварийный клапан: рассылка по нешаблонным текстам не должна съесть память.
    if len(_seen) > _MAX_TRACKED:
        for key in sorted(_seen, key=lambda k: _seen[k][0])[: len(_seen) - _MAX_TRACKED]:
            del _seen[key]


def is_broadcast(text: str, dialog_id: int) -> bool:
    """Этот текст уже ушёл во много диалогов — значит это рассылка, не менеджер."""
    key = _key(text)
    # Пустой текст (одно вложение, стикер) по тексту не сравнить — считаем ответом
    # человека: ошибиться в эту сторону безопаснее.
    if not key:
        return False
    now = time.time()
    _forget_old(now)
    first, dialogs = _seen.get(key, (now, set()))
    dialogs.add(dialog_id)
    _seen[key] = (first, dialogs)
    if len(dialogs) < _MIN_DIALOGS:
        return False
    logger.info(
        "исходящее опознано как рассылка — ИИ не глушим | диалогов=%d | текст=%r",
        len(dialogs), key[:60],
    )
    return True


def reset() -> None:
    """Сбросить счётчики (для тестов)."""
    _seen.clear()
