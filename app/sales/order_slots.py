# Порядок = порядок показа в блоке [Уже собрано]: как в воронке ОП1.
SLOT_LABELS: dict[str, str] = {
    "inscription": "надпись на изделии",
    "product": "изделие",
    "city": "город доставки",
    "color": "цвет",
    "size": "размер (рост/вес)",
    "recipient": "получатель (ФИО)",
    "phone": "телефон",
}

_PRODUCT_RE = re.compile(r"худи|толстовк|свитшот|футболк|лонгслив", re.I)


def _words(text: str) -> list[str]:
    return [w for w in re.split(r"\s+", (text or "").strip()) if w]


def _find_city(text: str) -> str | None:
    lowered = (text or "").lower()
    # Двусловные названия проверяем первыми: «нижний новгород» содержит «новгород».
    for city in sorted(_CITIES, key=len, reverse=True):
        if re.search(rf"(?<![а-яё]){re.escape(city)}(?![а-яё])", lowered):
            return city.capitalize()
    return None


def _find_color(text: str) -> str | None:
    for word in _words((text or "").lower()):
        clean = word.strip(".,!?;:«»\"'")
        if clean in _COLORS:
            return _COLORS[clean]
    return None


def _find_size(text: str) -> tuple[str, str] | None:
    """(рост, вес) в сантиметрах и килограммах, либо None."""
    height = _HEIGHT_RE.search(text or "")
    if not height:
        return None
    rest = (text or "")[: height.start()] + (text or "")[height.end():]
    weight = _WEIGHT_RE.search(rest)
    if not weight:
        return None
    return height.group(1), weight.group(1)


def has_size(text: str) -> bool:
    """Рост и вес названы в этом сообщении («180 80», «рост 180 вес 80»)."""
    return _find_size(text) is not None


def collect_slots(history: list[tuple[str, str]]) -> dict[str, str]:
    """Факты заказа из истории. history — [(role, text)] по возрастанию времени,
    role: 'client' для клиента, любое другое значение — наша сторона.

    Слот, названный позже, перекрывает более ранний: клиент имеет право передумать
    («я хочу толстовку» после свитшота в диалоге 51).
    """
    slots: dict[str, str] = {}
    asked: str | None = None

    for role, text in history:
        text = text or ""
        if role != "client":
            asked = "inscription" if ASKS_INSCRIPTION_RE.search(text) else None
            continue

        # Явные шаблоны — независимо от того, о чём мы спрашивали.
        phone = _PHONE_RE.search(text)
        if phone:
            slots["phone"] = re.sub(r"\D", "", phone.group(0))
        fio = _FIO_RE.search(text)
        if fio:
            slots["recipient"] = fio.group(0)
        size = _find_size(text)
        if size:
            # Рост и вес хранятся ещё и по отдельности: скрипт итогов заказа
            # печатает их разными строками ([Заказ.Рост] / [Заказ.Вес]).
            slots["height"], slots["weight"] = size
            slots["size"] = f"рост {size[0]} см, вес {size[1]} кг"
        city = _find_city(text)
        if city:
            slots["city"] = city
        color = _find_color(text)
        if color:
            slots["color"] = color
        product = _PRODUCT_RE.search(text)
        if product:
            slots["product"] = product.group(0).lower()

        # Надпись — единственный слот без собственного шаблона: на изделии может
        # быть что угодно. Её засчитываем по ответу на наш вопрос «какое имя или
        # фамилию напишем». Город и цвет так брать нельзя — в диалоге 52 клиент
        # ответил «чёрный» на вопрос про дизайн, и любой слот-по-очереди
        # записал бы это в дизайн.
        if (
            asked == "inscription"
            and "inscription" not in slots
            and "?" not in text
            and 0 < len(_words(text)) <= _MAX_ANSWER_WORDS
        ):
            slots["inscription"] = text.strip()
        asked = None

    return slots


# Плейсхолдеры CRM в текстах скриптов ОП. CRM у нас больше нет, подставлять их
# было нечем — и «Номер Вашего заказа: [Заказ.Номер]» вместе с «[Корзина]» и
# «[Доставка.ФИО]» уходили клиенту как есть (диалог 68, сообщения 964 и 978).
#
# Что знаем из диалога — подставляем, остальное вырезаем вместе со строкой:
# строка «Номер Вашего заказа:» без номера бессмысленна.
_CRM_PLACEHOLDER_RE = re.compile(r"\[(?:Заказ|Доставка|Корзина)[^\]]*\]")

# Предложение вместе с завершающей пунктуацией и пробелами после неё.
_SENTENCE_RE = re.compile(r"[^.!?]*(?:[.!?]+\s*|$)")
# Метка вместо плейсхолдера на время разбивки — без точек и прочей пунктуации.
_MARKER = "\x00"


def _cart_line(slots: dict[str, str]) -> str:
    parts = [slots.get("product") or "свитшот"]
    if slots.get("color"):
        parts.append(slots["color"])
    if slots.get("inscription"):
        parts.append(f"надпись «{slots['inscription']}»")
    return ", ".join(parts)


def render_order_placeholders(text: str, slots: dict[str, str]) -> str:
    """Подставить в текст данные заказа, собранные из диалога.

    Строку с плейсхолдером, для которого данных нет (номер заказа — его выдаёт
    учётная система, которой у нас нет), убираем целиком.
    """
    if not text or not _CRM_PLACEHOLDER_RE.search(text):
        return text

    known = {
        "[Доставка.ФИО]": slots.get("recipient", ""),
        "[Доставка.Телефон]": slots.get("phone", ""),
        "[Заказ.Рост]": f"рост {slots['height']} см" if slots.get("height") else "",
        "[Заказ.Вес]": f"вес {slots['weight']} кг" if slots.get("weight") else "",
        "[Заказ.Примечания (внутренние)]": (
            f"надпись «{slots['inscription']}»" if slots.get("inscription") else ""
        ),
        "[Корзина]": _cart_line(slots),
    }

    kept: list[str] = []
    for line in text.split("\n"):
        for token, value in known.items():
            if value:
                line = line.replace(token, value)
        if _CRM_PLACEHOLDER_RE.search(line):
            # Убираем только предложение с плейсхолдером: в скрипте 6 «Уточняем
            # СДЭК» номер заказа стоит в одной строке с благодарностью за заказ,
            # и выбрасывать её целиком значит потерять благодарность.
            #
            # Перед разбивкой плейсхолдер заменяем меткой: внутри «[Заказ.Номер]»
            # есть точка, и без этого предложение рвётся ровно по ней.
            masked = _CRM_PLACEHOLDER_RE.sub(_MARKER, line)
            line = "".join(
                part for part in _SENTENCE_RE.findall(masked) if _MARKER not in part
            ).strip()
            if not line:
                continue
        kept.append(line)

    # Схлопываем пустые строки, оставшиеся от вырезанных.
    return re.sub(r"\n{3,}", "\n\n", "\n".join(kept)).strip()


def format_slots_block(slots: dict[str, str]) -> str:
    """Блок для промпта. Пустой словарь → '' (вызывающий может не проверять)."""
    lines = [
        f"- {SLOT_LABELS[key]}: {slots[key]}"
        for key in SLOT_LABELS
        if slots.get(key)
    ]
    if not lines:
        return ""
    return (
        "[Уже собрано по заказу — НЕ переспрашивай это ни в какой формулировке]\n"
        + "\n".join(lines)
    )
