"""Имена статусов диалога, на которые опираются гейты воронки.

Статусы живут строками в таблице `dialog_statuses` и заводятся руками в админке,
а код принимает по ним решения: из какого статуса можно уйти в «Ждем предоплату»,
когда переключать воронку пингов, когда запрещать откат назад.

Сравнение шло по литералу «Горячий клиент». В проде статус называется «Горячий»
(id 3), а «Горячий клиент» (id 9) — пустой дубль без описания, который никто не
ставит. Из-за этого ВСЕ три гейта не срабатывали ни разу: статус свободно ездил
назад («Горячий» → «Есть расчет» → «Горячий», диалог 142), «Ждем предоплату» не
ставился никогда, а раз он не ставился — не вызывался и force_ping_funnel, и все
16 диалогов с пингами остались в воронке knows_price, включая тех, кто уже выбрал
способ оплаты и ждал счёт (замечание ОП от 10 августа, 14:12: «Тут надо бросать
диалог, должен подключаться менеджер и пинговать клиента индивидуально»).

Поэтому статус опознаётся не по одному литералу, а по набору синонимов: пока
заказчик не решил, какой из двух «горячих» оставить (вопрос В8 плана), код обязан
понимать оба.
"""

INTERESTED = "Поинтересовался"
CALCULATED = "Есть расчет"
AWAITING_PREPAY = "Ждем предоплату"
ORDER_CREATED = "Заказ оформлен"
NEEDS_CURATOR = "Нужен куратор"
BLACKLIST = "ЧС"

# Оба «горячих» из прода. Порядок важен: первое имя — то, которое мы ставим сами.
HOT_NAMES: tuple[str, ...] = ("Горячий", "Горячий клиент")

# Стадии, с которых разрешён переход в «Ждем предоплату»: клиент уже видел
# расчёт. Раньше сюда был записан только дубль «Горячий клиент», и живой
# «Горячий» в набор не попадал.
CAN_AWAIT_PREPAY: frozenset[str] = frozenset(
    (CALCULATED, AWAITING_PREPAY, ORDER_CREATED, *HOT_NAMES)
)

# Из «горячего» дорога одна — в предоплату. Любой другой next_status от модели
# сбрасывается, чтобы диалог не откатывался на шаг назад.
HOT_ALLOWED_NEXT: frozenset[str] = frozenset((AWAITING_PREPAY, *HOT_NAMES))


def is_hot(status_name: str | None) -> bool:
    """Диалог в «горячем» статусе — под любым из двух его имён."""
    return status_name in HOT_NAMES


def can_await_prepay(status_name: str | None) -> bool:
    """С этого статуса можно уходить в «Ждем предоплату»."""
    return status_name in CAN_AWAIT_PREPAY
