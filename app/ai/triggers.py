"""Триггеры эскалации: темы, которые ИИ не ведёт сам.

Вышивка — первая такая тема. Её стоимость считается отдельно по каждому элементу
дизайна (спина/грудь/рукав), цены высокие, и ошибка в расчёте дорого стоит: РОП
попросил, чтобы ИИ на эту тему сам не выходил, а на прямой вопрос клиента отвечал
общей формулировкой и передавал диалог менеджеру.

Статус ставим, но ответ не придерживаем: клиент получает нейтральную реплику
(«такой вариант нанесения есть, стоимость считаем по дизайну»), а куратор видит
диалог помеченным в списке. Придерживать ответ через need_curator тут нельзя —
диалог бы вставал на каждом упоминании вышивки.
"""
import re

CURATOR_STATUS_NAME = "Нужен куратор"

# По основе, а не по словоформам: «вышивка/вышивку/вышивкой/вышивке/вышивок»,
# «вышить», «вышивают», «вышивной». Граница слева нужна, чтобы не ловить
# «навышивать» в середине другого слова.
_EMBROIDERY_RE = re.compile(r"\bвышив|\bвышит|\bвышью|\bвышьет", re.IGNORECASE)

# Опт: ИИ путается в оптовых ценах — на 10 свитшотов назвала 4590₽/шт, а следом на
# «дорого» выдала «дополнительную скидку» 4990₽, то есть дороже собственного
# предложения. Оптовую цену считает менеджер.
WHOLESALE_MIN_QTY = 3

# Явная заявка на партию — считаем оптом независимо от количества.
_WHOLESALE_WORDS_RE = re.compile(
    r"\bопт\b|\bоптом\b|\bоптов|\bна коллектив|\bкоманд[уые]\b|\bкорпоратив",
    re.IGNORECASE,
)

# Количество + изделие: «10 свитшотов», «5 шт». Двузначным ограничения нет, но
# четырёхзначное — это цена («4990 рублей»), а не количество, поэтому не больше трёх цифр.
_QTY_RE = re.compile(
    r"(?<!\d)(\d{1,3})\s*(?:шт|штук|единиц|издели|свитшот|худи|толстов|кофт|футбол|лонгслив)",
    re.IGNORECASE,
)

# Числительные словами. «Пара»/«парные» намеренно НЕ здесь: парный комплект —
# обычный товар из прайса, а не опт.
_QTY_WORDS = {
    "три": 3, "трех": 3, "трёх": 3, "четыре": 4, "четырех": 4, "пять": 5, "пяти": 5,
    "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10, "десятка": 10,
    "двадцать": 20, "тридцать": 30, "сорок": 40, "пятьдесят": 50, "сто": 100,
}
_QTY_WORDS_RE = re.compile(
    r"\b(" + "|".join(_QTY_WORDS) + r")\b\s*(?:шт|штук|единиц|издели|свитшот|худи|толстов|кофт)",
    re.IGNORECASE,
)


def mentions_embroidery(text: str | None) -> bool:
    """Клиент заговорил о вышивке — диалог передаём менеджеру."""
    return bool(_EMBROIDERY_RE.search((text or "").replace("ё", "е")))


def mentions_wholesale(text: str | None) -> bool:
    """Клиент просит партию — цену считает менеджер, не ИИ.

    Порог — WHOLESALE_MIN_QTY изделий (решение РОПа). Заказ на одного-двоих ИИ
    ведёт сам: пара изделий «себе и мужу» — типовой сценарий и есть в прайсе
    отдельной позицией, эскалировать его значило бы дёргать менеджера на каждом
    втором диалоге.
    """
    normalized = (text or "").replace("ё", "е")
    if _WHOLESALE_WORDS_RE.search(normalized):
        return True
    if any(int(n) >= WHOLESALE_MIN_QTY for n in _QTY_RE.findall(normalized)):
        return True
    return any(
        _QTY_WORDS[w.lower()] >= WHOLESALE_MIN_QTY
        for w in _QTY_WORDS_RE.findall(normalized)
    )


# Срочность: производство 10-14 дней плюс доставка, уложиться в неделю можно
# только вручную — договорившись на производстве. Обещать это ИИ не может.
_URGENT_RE = re.compile(
    r"\bсрочн|\bпосрочн|\bгорит\b|\bкак можно скорее|\bкак можно быстрее|"
    r"\bуспе(?:ть|ем|ете)\b|\bнужно к \d|\bнадо к \d|\bк \d{1,2}\s*(?:числ|-?м[уи])|"
    r"\b(?:за|через)\s+(?:\d+\s*)?(?:день|дня|дней|недел)",
    re.IGNORECASE,
)


# Срок днём недели или ближайшей датой без слова «срочно».
_DEADLINE_RE = re.compile(
    r"\bкритичн|\bна этой неделе\b|\bдо конца недели\b|"
    r"\bк\s+(?:понедельник|вторник|сред[еу]|четверг|пятниц[ае]|суббот[еы]|воскресень)",
    re.IGNORECASE,
)

# «Мне нужно завтра» — тот же несбыточный срок, только без слова «срочно»: в
# диалоге 90 (11:56) триггер промолчал, и ИИ отказал клиенту сам, вместо того
# чтобы позвать менеджера. Одного «завтра» мало: «напишу завтра» и «давайте
# завтра созвонимся» — не про срок заказа, поэтому рядом требуется слово про
# потребность.
_NEED_WORDS = r"нужн\w*|надо|хоч\w+|успе\w+|получ\w+|готов\w*|привез\w+|доставить|срок\w*"
_SOON_WORDS = r"сегодня|завтра|послезавтра|завтрашн\w*"
_NEAR_DEADLINE_RE = re.compile(
    rf"(?:{_NEED_WORDS})(?:\W+\w+){{0,3}}\W+(?:{_SOON_WORDS})"
    rf"|(?:{_SOON_WORDS})(?:\W+\w+){{0,3}}\W+(?:{_NEED_WORDS})",
    re.IGNORECASE,
)


def mentions_urgency(text: str | None) -> bool:
    """Клиент называет срок, в который стандартное производство не укладывается."""
    normalized = (text or "").replace("ё", "е")
    return bool(
        _URGENT_RE.search(normalized)
        or _DEADLINE_RE.search(normalized)
        or _NEAR_DEADLINE_RE.search(normalized)
    )


# Возврат предоплаты и отмена оплаченного заказа. Возвратов у нас нет, на первую
# просьбу отвечает скрипт «Возражение: Возврат предоплаты» (подарок или скидка
# вместо возврата) — и на этом ИИ с темы уходит.
#
# Дальше он её не тянет: в диалоге 68 клиент попросил вернуть предоплату, получил
# скрипт, написал «?» — и ИИ сам предложил «Подтвердите, пожалуйста: отменяем
# заказ окончательно?». Отменять оплаченные заказы ИИ не уполномочен, а клиент на
# это «да» и ответил.
_REFUND_RE = re.compile(
    # «ё» в шаблонах не нужна — на входе она уже заменена на «е».
    r"верн(?:уть|ите|ете)\s+(?:мне\s+)?(?:деньг|предоплат|оплат|сумм|аванс)|"
    r"возврат\s+(?:денег|предоплаты|оплаты|средств)|"
    r"деньги\s+назад|отмен(?:ить|яем|ите)\s+заказ|"
    r"передумал\w*.{0,30}верн|"
    r"хочу\s+отказаться\s+от\s+заказа",
    re.IGNORECASE,
)


def mentions_refund(text: str | None) -> bool:
    """Клиент просит вернуть деньги или отменить оплаченный заказ."""
    return bool(_REFUND_RE.search((text or "").replace("ё", "е")))


# Места, на которые мы не наносим. Женя, 03.08: «например, мы не можем наносить
# принт на манжету». Обещать такое нанесение нельзя: клиент согласует дизайн,
# внесёт предоплату, а на производстве выяснится, что так не шьют.
_IMPOSSIBLE_PLACEMENT_RE = re.compile(
    r"\bманжет|\bрезинк[еауи]\b|\bворотник|\bкапюшон\w*\s+(?:внутри|изнутри)|"
    r"\bмолни[июе]\b|\bкарман\w*\s+внутри",
    re.IGNORECASE,
)

# Размерная сетка. Женя, 03.08: «по нестандартным размерам — на вес больше 110 кг
# лучше звать менеджера». Ниже 40 кг — то же самое: детских лекал у нас нет.
_MAX_WEIGHT_KG = 110
_MIN_WEIGHT_KG = 40
# Вес с единицей или со словом «вес» — самый надёжный признак.
_WEIGHT_UNIT_RE = re.compile(r"(?<!\d)(\d{2,3})\s*(?:кг|kg)(?!\d)", re.IGNORECASE)
_WEIGHT_WORD_RE = re.compile(
    r"(?:вес\w*|вешу|весит|вешает)\D{0,4}(\d{2,3})(?!\d)", re.IGNORECASE,
)
# Голые числа: «180 125» — рост и вес. Без роста рядом голое число весом не
# считаем, иначе «300 рублей» и «250 за доставку» уводили бы диалог к куратору.
_NUMBER_RE = re.compile(r"(?<!\d)(\d{2,3})(?!\d)")
_HEIGHT_MIN, _HEIGHT_MAX = 140, 220


def mentions_impossible_placement(text: str | None) -> bool:
    """Клиент просит нанесение туда, где мы не печатаем."""
    return bool(_IMPOSSIBLE_PLACEMENT_RE.search((text or "").replace("ё", "е")))


def _out_of_grid(weight: int) -> bool:
    return weight > _MAX_WEIGHT_KG or weight < _MIN_WEIGHT_KG


def oversize(text: str | None) -> bool:
    """Вес вне размерной сетки — размер подбирает менеджер, не ИИ."""
    raw = text or ""
    for rx in (_WEIGHT_UNIT_RE, _WEIGHT_WORD_RE):
        if any(_out_of_grid(int(n)) for n in rx.findall(raw)):
            return True
    # «180 125» — пара роста с весом. Вес засчитываем только когда рост назван
    # рядом: одинокое число в реплике — это чаще цена, чем килограммы.
    numbers = [int(n) for n in _NUMBER_RE.findall(raw)]
    if not any(_HEIGHT_MIN <= n <= _HEIGHT_MAX for n in numbers):
        return False
    return any(
        _out_of_grid(n) for n in numbers
        if not (_HEIGHT_MIN <= n <= _HEIGHT_MAX) and 20 <= n <= 300
    )


def curator_trigger(text: str | None) -> str | None:
    """Название сработавшего триггера эскалации, либо None."""
    if mentions_embroidery(text):
        return "вышивка"
    if mentions_wholesale(text):
        return "опт"
    if mentions_refund(text):
        return "возврат предоплаты"
    if mentions_urgency(text):
        return "срочный заказ"
    if mentions_impossible_placement(text):
        return "нанесение, которое мы не делаем"
    if oversize(text):
        return "нестандартный размер"
    return None
