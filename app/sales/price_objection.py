"""Возражение «дорого»: когда отрабатывать ценностью, а когда уступать в цене.

Регламент ОП (10 августа, разбор диалогов менеджеров):

    5990 → отработка ценностью → ПОВТОРНОЕ ценовое возражение → 5490 →
    ПОВТОРНОЕ ценовое возражение → 4990.

Ключевое слово — «повторное». Скидка разрешена только после того, как мы уже
объяснили ценность, а клиент СНОВА уперся в цену. Сомнение сомнению рознь:

- «Понятно», «Хорошо», «Ясно», «Спасибо» — нейтральная реакция. Скидки нет.
- «Подумаю», «Надо посмотреть» — тоже нейтральная: надо уточнить, что именно
  смущает, а не сбрасывать цену. «Возможно, теперь вопрос касается дизайна».
- «А какие размеры есть?», «А доставка сколько?», «Давайте тогда» — клиент ушёл
  с темы цены на товар и заказ. Это ПОЛОЖИТЕЛЬНАЯ реакция, скидки нет.
- «Всё равно дорого», «За 5990 точно не возьму», «У других дешевле» — ценовое
  сопротивление сохранилось. Только это открывает следующую ступень.

Модуль отвечает на один вопрос: можно ли в этом ходу показать скидочный скрипт.
Сама ступень (5490 или 4990) считается отдельно — по уже названной цене,
см. app.sales.price_placeholder.
"""
import logging
import re

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.models import Message, MessageRole
from app.vk.outgoing import was_delivered

logger = logging.getLogger(__name__)

# Прямое сопротивление цене. Список собран из живых диалогов менеджеров.
_PRICE_OBJECTION_RE = re.compile(
    r"дорог\w*"                                   # дорого, дороговато, у вас дорого
    r"|деш[её]вл\w*"                              # дешевле, нашёл дешевле
    r"|не\s+сто\w+\s+(?:он\s+|это\s+)?(?:таких\s+|этих\s+)?денег"
    r"|не\s+готов\w*\s+(?:столько|такое|такую)"
    r"|за\s+так(?:ую|ой)\s+цен\w+\s+не"
    r"|рассчитыва\w+\s+(?:максимум\s+)?на\s+\d"
    r"|бюджет\w*\s+до\s+\d"
    r"|\bвб\b|озон\w*|валберис|wildberries|маркетплейс\w*",
    re.I,
)

# «За 5990 точно не возьму», «Нет, за такую цену не надо» — отказ, привязанный к
# сумме. Без суммы «не возьму» может относиться к чему угодно.
_REFUSAL_AT_PRICE_RE = re.compile(
    r"(?:за\s+)?\d[\d\s ]{2,7}\s*(?:₽|руб\w*)?\s*(?:точно\s+)?не\s+(?:возьму|буду|надо|нужно)"
    r"|не\s+(?:возьму|буду\s+брать)\s+за\s+\d",
    re.I,
)

# Нейтральная реакция: клиент не спорит, но и не согласился. Скидку не даём —
# уточняем, что именно смущает.
_NEUTRAL_RE = re.compile(
    r"^\W*(?:понятно|ясно|хорошо|хорошо[, ]+понял\w*|окей|ок|спасибо|"
    r"подума\w+|надо\s+подума\w+|над[оа]\s+посмотр\w+|я\s+ещ[ёе]\s+посмотрю|"
    r"посмотрю|буду\s+иметь\s+в\s+виду)\W*$",
    re.I,
)


def is_price_objection(text: str | None) -> bool:
    """Клиент сопротивляется цене — это не «подумаю» и не вопрос о товаре."""
    raw = (text or "").strip()
    if not raw or _NEUTRAL_RE.match(raw):
        return False
    normalized = raw.replace("ё", "е")
    return bool(
        _PRICE_OBJECTION_RE.search(normalized) or _REFUSAL_AT_PRICE_RE.search(normalized)
    )


def is_neutral_reaction(text: str | None) -> bool:
    """«Понятно», «Подумаю» — повод уточнить, а не повод сбросить цену."""
    return bool(_NEUTRAL_RE.match((text or "").strip()))


# Сколько последних сообщений разбираем. Возражение и его отработка идут подряд,
# полную историю ради этого тянуть незачем.
_HISTORY_LIMIT = 40


async def concession_allowed(
    db: AsyncSession, dialog_id: int, client_text: str,
) -> bool:
    """Можно ли в этом ходу предложить следующую ступень скидки.

    Условия ровно из регламента: текущая реплика — ценовое возражение, до неё
    клиент уже возражал по цене, и между двумя возражениями мы успели ответить
    (та самая отработка ценностью). Первое «дорого» скидки не открывает.
    """
    if not is_price_objection(client_text):
        return False

    rows = await db.execute(
        select(Message)
        .where(Message.dialog_id == dialog_id)
        .order_by(Message.id.desc())
        .limit(_HISTORY_LIMIT)
    )
    history = [
        m for m in reversed(rows.scalars().all())
        if m.role == MessageRole.client or was_delivered(m)
    ]

    # Идём от свежего к старому. Текущая реплика встречается первой — на ней
    # мы ещё ничего не ответили, поэтому она сама себя не засчитывает. Дальше
    # нужна наша реплика (отработка), а до неё — предыдущее ценовое возражение.
    we_answered_since = False
    for msg in reversed(history):
        if msg.role in (MessageRole.ai, MessageRole.curator):
            we_answered_since = True
        elif msg.role == MessageRole.client and we_answered_since:
            if is_price_objection(msg.text):
                logger.info(
                    "dialog=%s: возражение по цене повторное — скидка разрешена", dialog_id,
                )
                return True
    return False
