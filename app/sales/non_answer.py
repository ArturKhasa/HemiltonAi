"""Реплика, которая ответом не является.

Диалог 756, 20 августа. На «какое имя или фамилию напишем на кофте?» клиент
написал «М?», и ИИ ответил «Супер, зафиксировала» и отправил следом стоимость и
доставку. Клиент написал «Чего?» — и получил «Супер, зафиксировала! В какой
город нужна доставка?». Через минуту он спросил, бот с ним говорит или человек.

Уверенность модели на этих ходах была 0.99: она не сомневалась. Живой менеджер
на «Чего?» переспрашивает, а не фиксирует заказ, поэтому решаем это кодом, а не
уговорами в промпте.

За неделю из 97 наших реплик со словом «зафиксировала» десять ушли в ответ на
реплику короче пяти символов и четыре — в ответ на встречный вопрос.
"""
import re

# Переспрос: «что?», «чего?», «а?», «не понял», «в смысле», «о чём вы».
_CONFUSED_RE = re.compile(
    r"^\W*(?:"
    r"[аaэ]|м|ну|что|чего|че|чо|как|куда|кого|зачем|почему|при\s*чём|при\s*чем"
    r"|не\s*пон(?:ял|яла|имаю)|непон(?:ятно|ял)|в\s*смысле|о\s*чём|о\s*чем"
    r"|вы\s*о\s*ч[её]м|о\s*ч[её]м\s*вы|это\s*что|што"
    r")\W*$",
    re.I,
)

# Одинокий знак препинания: «?», «??», «...».
_PUNCTUATION_ONLY_RE = re.compile(r"^[\W_]+$")

# Пометка вложения без текста — на вопрос она тоже не отвечает, но и переспроса
# не требует: фото клиент прислал осмысленно.
_ATTACHMENT_ONLY_RE = re.compile(r"^\[[^\]]+\]$")


def is_non_answer(text: str) -> bool:
    """Клиент не ответил на вопрос, а переспросил или отозвался невнятно."""
    value = (text or "").strip()
    if not value or _ATTACHMENT_ONLY_RE.match(value):
        return False
    if _PUNCTUATION_ONLY_RE.match(value):
        return True
    return bool(_CONFUSED_RE.match(value))


# Знак вопроса в ответе — то, что отличает встречный вопрос от согласия.
# «+» — кодовое слово из рекламы («кодовые слова: начать, +, /start»), и в
# ответах на вопрос про надпись их 59 из 62 за две недели. Отправлять такого
# клиента менеджеру не за что: он не спрашивает, он соглашается.
_QUESTION_MARK_RE = re.compile(r"\?")


def is_counter_question(text: str) -> bool:
    """Клиент ответил на наш вопрос вопросом.

    Лена, 26.08: «Если вопросом на вопрос, то лучше адресовать менеджеру, потому
    что таких диалогов почти нет, а если есть это чет неадекватное скорее всего».

    Считаем встречным вопросом две вещи: голую пунктуацию со знаком вопроса
    («?», «???», «)?») и прямой переспрос словами («Чего?», «Не понял», «м»).
    Согласие без вопроса — «+», «👍», «.» — сюда не попадает, хотя ответом на
    вопрос про надпись тоже не является: воронку оно держит (is_non_answer),
    но человека не зовёт.

    По боевой базе за две недели правило срабатывает в 22 диалогах из 3 225.
    """
    value = (text or "").strip()
    if not value or _ATTACHMENT_ONLY_RE.match(value):
        return False
    if _PUNCTUATION_ONLY_RE.match(value):
        return bool(_QUESTION_MARK_RE.search(value))
    return bool(_CONFUSED_RE.match(value))
