async def get_system_prompt(
    db: AsyncSession,
    name: str = "sales",
    type_id: int | None = None,
) -> str:
    q = select(PromptVersion).where(PromptVersion.is_active == True)
    if type_id is not None:
        q = q.where(PromptVersion.type_id == type_id)
    else:
        q = q.where(PromptVersion.name == name)
    result = await db.execute(q.order_by(PromptVersion.id.desc()).limit(1))
    row = result.scalar_one_or_none()
    if row:
        return row.content + "\n" + _SALES_PROMPT_FALLBACK
    return _SALES_PROMPT_FALLBACK
