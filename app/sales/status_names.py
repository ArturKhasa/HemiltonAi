"""Имена статусов диалога и лестница, по которой диалог по ним поднимается.

Статусы живут строками в таблице `dialog_statuses` и заводятся в админке, а код
принимает по ним решения. Раньше статус ставила ТОЛЬКО модель полем
`next_status`, и это не работало сразу по двум причинам (замеры по проду за две
недели, 27.08):

* половину пути клиент проходит вообще без модели — приветствие уходит скриптом,
  расчёт за ним отправляет связка `follow_up_script_id`, молчуну цену досылает
  `app.ping.silent_greeting`, дальше работают пинги. 218 диалогов получили
  расчёт и остались в стартовом статусе, потому что ни один из этих путей к
  статусу не прикасается;
* когда модель всё-таки работает, `next_status` она заполняет в 45 % ходов:
  «оставить как есть» для неё всегда безопаснее.

Итог: 834 диалога с тремя и более сообщениями клиента висели в
«Поинтересовался» против 89 в «Есть расчет».

Поэтому ступени воронки теперь считает код по фактам
(`app.sales.status_flow`), а модели остаются только боковые статусы, которые из
фактов диалога не выводятся: «Нужен куратор», «Спам», «ЧС».
"""

INTERESTED = "Поинтересовался"
CALCULATED = "Есть расчет"
# Клиент ответил после расчёта — назвал город доставки, цвет, размер. Статус
# заведён по просьбе ОП 27.08: между «Есть расчет» и «Горячий» была дыра
# длиной в половину воронки.
CLARIFYING = "Уточняем детали"
HOT = "Горячий"
# Запросили ФИО и телефон получателя — скрипт «5.1 Данные перед оформлением».
AWAITING_DATA = "Ждем данные"
AWAITING_PREPAY = "Ждем предоплату"
ORDER_CREATED = "Заказ оформлен"
NEEDS_CURATOR = "Нужен куратор"
SPAM = "Спам"
BLACKLIST = "ЧС"

# Оба «горячих» из прода: id 3 «Горячий» и id 9 «Горячий клиент» — пустой дубль
# без описания, из-за которого когда-то не срабатывали все три гейта воронки.
# Дубль гасится миграцией 054, но имя остаётся известным коду: на старых
# диалогах оно ещё встречается.
HOT_NAMES: tuple[str, ...] = (HOT, "Горячий клиент")

# Лестница воронки, снизу вверх. Порядок — это и есть правило перехода: диалог
# поднимается на ступень, факт которой подтверждён, и никогда не спускается.
# Смысл ступеней задан отделом продаж 27.08 и продублирован в описаниях статусов
# (миграция 054) — модель читает именно их.
LADDER: tuple[str, ...] = (
    INTERESTED,
    CALCULATED,
    CLARIFYING,
    HOT,
    AWAITING_DATA,
    AWAITING_PREPAY,
    ORDER_CREATED,
)

_RANK: dict[str, int] = {name: i for i, name in enumerate(LADDER)}
# Старый дубль читается как та же ступень, что и «Горячий»: иначе диалог,
# доставшийся нам на нём, лестница посчитала бы стоящим ниже всех и подняла бы
# «назад» в «Есть расчет».
_RANK["Горячий клиент"] = _RANK[HOT]

# Боковые статусы: из фактов переписки не выводятся, ставятся своими ветками
# (триггеры менеджерских тем, эскалация пинга, отписка от сообщества). Лестница
# их не перетирает и из них не выводит — диалог, переданный человеку, обязан
# остаться переданным.
SIDE_STATUSES: frozenset[str] = frozenset((NEEDS_CURATOR, SPAM, BLACKLIST))

# Что модели вообще разрешено предлагать в `next_status`. Ступени лестницы сюда
# не входят: их считает код, и предложение модели по ним игнорируется.
MODEL_STATUSES: frozenset[str] = SIDE_STATUSES


def is_hot(status_name: str | None) -> bool:
    """Диалог в «горячем» статусе — под любым из двух его имён."""
    return status_name in HOT_NAMES


def rank(status_name: str | None) -> int:
    """Номер ступени. Всё, чего нет в лестнице (боковые статусы, None,
    выключенный статус из админки), — ниже нулевой ступени: подниматься с них
    лестница не мешает, а решение «трогать ли вообще» принимается отдельно."""
    return _RANK.get(status_name or "", -1)


def is_ladder(status_name: str | None) -> bool:
    """Статус — ступень воронки, а не боковая ветка."""
    return (status_name or "") in _RANK
