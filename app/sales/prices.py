"""Суммы в тексте.

Жило в `app.ai.runner` приватной парой `_MONEY_RE` / `_prices_in`: ход модели
сверяет по ним, не ушла ли цена второй раз. Ровно тот же вопрос — «клиент уже
видел сумму?» — задаёт лестница статусов (`app.sales.status_flow`), а тянуть
ради него весь runner она не может: он импортирует пол-пакета и сам импортирует
воронку.
"""
import re

# Сумма — это число, за которым идёт рубль в любом написании: «4 990 ₽»,
# «5490р», «8.980 руб». Голое число ценой не считается: рост, вес и номер дома
# клиент пишет так же.
_MONEY_RE = re.compile(
    r"\d[\d\s .]{2,7}(?=\s*(?:₽|руб|р(?![а-яё])))", re.IGNORECASE
)


def prices_in(text: str) -> set[str]:
    """Суммы в тексте, нормализованные: «4 990 ₽» и «4990руб» — одно и то же."""
    return {re.sub(r"\D", "", m) for m in _MONEY_RE.findall(text or "")}


# «(вместо 7 990 ₽)», «взамен 12 480 руб» — зачёркнутая цена. Она в тексте есть
# всегда и всегда больше настоящей: считать её суммой заказа нельзя.
_STRUCK_RE = re.compile(
    r"(?:вместо|взамен)\s*\d[\d\s .]{2,7}\s*(?:₽|руб\w*|р(?![а-яё]))", re.IGNORECASE
)

# Ниже тысячи — не цена изделия: доставка «от 890₽», бронь «500 рублей», первая
# оплата «800 руб». Все они стоят в тех же сообщениях, что и сумма заказа.
_MIN_ORDER_AMOUNT = 1000


def order_amounts(text: str) -> list[int]:
    """Суммы из текста, годные на роль цены заказа: без зачёркнутых и без мелочи."""
    return sorted(
        {
            int(digits)
            for digits in (re.sub(r"\D", "", m) for m in _MONEY_RE.findall(_STRUCK_RE.sub(" ", text or "")))
            if digits and int(digits) >= _MIN_ORDER_AMOUNT
        }
    )


def order_total(texts_newest_first) -> int | None:
    """Во сколько обошёлся заказ по последнему нашему расчёту.

    Берём ПОСЛЕДНЕЕ наше сообщение, в котором вообще есть цена, и внутри него —
    наибольшую сумму. Именно так устроены оба ценовых скрипта: обычный называет
    одну цену, а тегированный под комплект перечисляет части и следом итог
    («Толстовка - 5490р, Жилетка - 3490р, Комплект из двух изделий со скидкой -
    8.980р»). Наибольшая в сообщении — это и есть итог.

    Последнее, а не наибольшее за диалог: после возражения «дорого» цена идёт
    вниз (5 990 → 5 490 → 4 990), и заказ стоит столько, сколько названо
    последним.
    """
    for text in texts_newest_first:
        amounts = order_amounts(text)
        if amounts:
            return amounts[-1]
    return None
