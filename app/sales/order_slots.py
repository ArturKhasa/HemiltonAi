"""Что клиент уже сообщил по заказу — город, цвет, размер, надпись, получатель.

Модель переспрашивает то, что уже знает: в диалоге 52 она пять ходов подряд
спрашивала «какой дизайн нанесём на кофту?», а скрипт доставки уточнил город,
названный клиентом двумя минутами раньше. Историю она видит целиком, но собрать
из неё список фактов на каждом ходу — ровно та работа, которую она и не делает.

Поэтому факты собираются кодом и подаются готовым блоком [Уже собрано]. Тот же
разбор нужен и связкам скриптов: они уходят клиенту дословно, и вопрос про город
внутри «2.3 Доставка» нельзя задавать, если город уже назван.

Разбор нарочно консервативный: слот заполняется, только когда ответ клиента идёт
следом за нашим вопросом про этот слот, либо совпал с явным шаблоном (телефон,
рост/вес, город из списка). Лишний вопрос неприятен, но выдуманный за клиента
факт — хуже.
"""
import re

# Наш вопрос про надпись — «какое имя или фамилию напишем на Вашей кофте?»
# (скрипт 1.2 воронки ОП1) и его вариации.
ASKS_INSCRIPTION_RE = re.compile(r"им[яе].{0,20}фамили|напишем на|как(?:ую|ая) надпис", re.I)

# О чём спрашивает звено связки. Скрипты уходят клиенту дословно, поэтому
# «2.3 Доставка» спрашивает город, а «5.1 Данные перед оформлением» — ФИО с
# телефоном, даже когда клиент назвал их минуту назад. Звено с вопросом про уже
# заполненный слот пропускаем целиком (см. asked_slot).
_ASKS_SLOT: dict[str, re.Pattern] = {
    "city": re.compile(r"в как(?:ой|ом) город|город.{0,15}доставк|куда.{0,10}доставл", re.I),
    "recipient": re.compile(r"фио.{0,30}телефон|телефон.{0,30}фио", re.I),
    "size": re.compile(r"(?=.*\bрост)(?=.*\bвес)", re.I | re.S),
}

# Отдельно — для проверок вне цепочки скриптов.
ASKS_CITY_RE = _ASKS_SLOT["city"]


def asked_slot(text: str) -> str | None:
    """Какой факт заказа спрашивает этот текст, либо None."""
    for slot, rx in _ASKS_SLOT.items():
        if rx.search(text or ""):
            return slot
    return None


def slot_is_filled(slot: str, slots: dict[str, str]) -> bool:
    """Слот «recipient» закрыт только когда есть и ФИО, и телефон: скрипт
    спрашивает их одной фразой, и половины ответа для пропуска мало."""
    if slot == "recipient":
        return bool(slots.get("recipient") and slots.get("phone"))
    return bool(slots.get(slot))

# Короткий ответ на вопрос: реплика из одного-трёх слов без вопросительного знака.
# Длинную фразу как ответ не засчитываем — там может быть встречный вопрос.
_MAX_ANSWER_WORDS = 4

_PHONE_RE = re.compile(r"(?:\+7|8|7)[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}")
# «рост 180 вес 60», «180 и 60», «100 179» — два числа человеческого диапазона.
_HEIGHT_RE = re.compile(r"(?<!\d)(1[4-9]\d|20\d)(?!\d)")
_WEIGHT_RE = re.compile(r"(?<!\d)([4-9]\d|1[0-5]\d)(?!\d)")
# «ФИО»: три слова с заглавной буквы подряд.
_FIO_RE = re.compile(r"\b[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\b")

