"""Эскалация по теме вышивки.

РОП: «я бы запретила ии самостоятельно задавать вопрос о вышивке, потому что там
сложные расчёты и большие цены. По вышивке в диалоге должен подключиться менеджер».
"""
import pytest

from app.ai.triggers import curator_trigger, mentions_embroidery, mentions_urgency, mentions_wholesale


@pytest.mark.parametrize(
    "text",
    [
        "Вышивку",                              # реальная реплика из диалога 9
        "а вышивка у вас есть?",
        "хочу с вышивкой на спине",
        "сколько стоит вышивка герба",
        "интересует объёмная вышивка",          # с ё
        "можно вышить фамилию?",
        "что дешевле, принт или вышивание",
        "ВЫШИВКА",                              # регистр
        "Вышивкой можно?",
    ],
)
def test_detected(text):
    assert mentions_embroidery(text) is True


@pytest.mark.parametrize(
    "text",
    [
        "хочу термопринт",
        "давайте просто надпись",
        "а размеры какие есть?",
        "",
        None,
        "вышел из чата",       # «выш» + другое слово — основа не совпадает
        "вышлите счёт",        # частая реплика: «вышлите» ≠ «вышить»
        "вышло дороговато",
    ],
)
def test_not_detected(text):
    assert mentions_embroidery(text) is False


@pytest.mark.parametrize(
    "text",
    [
        "я хочу 10 свитшотов, какая скидка?",   # реальная реплика Жени
        "нужен опт",
        "интересует оптовая цена",
        "закажем оптом на команду",
        "нам надо 25 худи",
        "50 штук сделаете?",
        "хотим на коллектив",
        "нужно 3 свитшота",                     # ровно порог
        "три худи сделаете?",                   # числительное словом
        "нам на корпоратив",
    ],
)
def test_wholesale_detected(text):
    assert mentions_wholesale(text) is True


@pytest.mark.parametrize(
    "text",
    [
        "хочу один свитшот",
        "а сколько стоит?",
        "мне 4990 подходит",       # цена, а не количество
        "",
        None,
        "оптика запотела",         # «опт» внутри слова — граница не совпадает
        # Ниже порога: заказ на себя и близкого ИИ ведёт сам.
        "хочу 2 свитшота",
        "два худи, мне и мужу",
        "нужны парные свитшоты",   # парный комплект — позиция прайса, не опт
        "свитшот парные 9990",
    ],
)
def test_wholesale_not_detected(text):
    assert mentions_wholesale(text) is False


def test_trigger_name_reported():
    assert curator_trigger("а вышивка есть?") == "вышивка"
    assert curator_trigger("хочу 10 свитшотов") == "опт"
    assert curator_trigger("какой цвет посоветуете?") is None


@pytest.mark.parametrize(
    "text",
    [
        "мне надо уже через неделю",          # реальная реплика Жени
        "срочно нужно",
        "а срочный заказ сделаете?",
        "успеем к 10 числу?",
        "нужно к 5 сентября",
        "как можно быстрее",
        "за 3 дня реально?",
    ],
)
def test_urgency_detected(text):
    assert mentions_urgency(text) is True


@pytest.mark.parametrize(
    "text",
    [
        "сколько по времени изготовление?",   # обычный вопрос про сроки — не срочность
        "а когда будет готово?",
        "не срочно, спокойно",                 # «не срочно» ловится, см. коммент ниже
        "",
        None,
    ],
)
def test_urgency_not_detected(text):
    if text == "не срочно, спокойно":
        pytest.skip("«не срочно» отличать от «срочно» регуляркой не выйдет — эскалация "
                    "лишний раз безопаснее пропущенного срочного заказа")
    assert mentions_urgency(text) is False


class TestRefundTrigger:
    """Возвратов у нас нет. На первую просьбу отвечает скрипт «Возражение:
    Возврат предоплаты», дальше тему ведёт куратор: в диалоге 68 ИИ, оставленный
    на этой теме, сам предложил «отменяем заказ окончательно?» — и получил «да».
    """

    @pytest.mark.parametrize("text", [
        "передумал можно оплату вернуть ?",
        "верните деньги",
        "хочу вернуть предоплату",
        "можно возврат денег?",
        "отмените заказ",
        "хочу отказаться от заказа",
        "верните мне сумму",
    ])
    def test_refund_escalates(self, text):
        assert curator_trigger(text) == "возврат предоплаты"

    @pytest.mark.parametrize("text", [
        "когда вернётесь с ответом?",
        "а деньги когда списываются?",
        "оплата при получении?",
        "верните пожалуйста прежний дизайн",
    ])
    def test_unrelated_not_escalated(self, text):
        assert curator_trigger(text) != "возврат предоплаты"
