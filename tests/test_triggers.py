"""Эскалация по теме вышивки.

РОП: «я бы запретила ии самостоятельно задавать вопрос о вышивке, потому что там
сложные расчёты и большие цены. По вышивке в диалоге должен подключиться менеджер».
"""
import pytest

from app.ai.triggers import mentions_embroidery


@pytest.mark.parametrize(
    "text",
    [
        "Вышивку",                              # реальная реплика из диалога 9
        "а вышивка у вас есть?",
        "хочу с вышивкой на спине",
        "сколько стоит вышивка герба",
        "интересует объёмная вышивка",          # с ё
        "можно вышить фамилию?",
        "что дешевле, принт или вышивание",
        "ВЫШИВКА",                              # регистр
        "Вышивкой можно?",
    ],
)
def test_detected(text):
    assert mentions_embroidery(text) is True


@pytest.mark.parametrize(
    "text",
    [
        "хочу термопринт",
        "давайте просто надпись",
        "а размеры какие есть?",
        "",
        None,
        "вышел из чата",       # «выш» + другое слово — основа не совпадает
        "вышлите счёт",        # частая реплика: «вышлите» ≠ «вышить»
        "вышло дороговато",
    ],
)
def test_not_detected(text):
    assert mentions_embroidery(text) is False
